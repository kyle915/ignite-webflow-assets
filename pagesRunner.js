  function currentPath() {
    var p = (location.pathname || "").replace(/\/+$/, "").toLowerCase();
    return p === "" ? "/" : p;
  }

  function loadScript(src, isLoaded) {
    return new Promise(function (resolve, reject) {
      if (typeof isLoaded === "function" && isLoaded()) return resolve();
      var existing = document.querySelector('script[data-ignite-src="' + src + '"]');
      if (existing) {
        if (existing.dataset.loaded === "1") return resolve();
        existing.addEventListener("load", function () { resolve(); });
        existing.addEventListener("error", function () { reject(new Error("failed " + src)); });
        return;
      }
      var s = document.createElement("script");
      s.src = src;
      s.setAttribute("data-ignite-src", src);
      s.onload = function () { s.dataset.loaded = "1"; resolve(); };
      s.onerror = function () { reject(new Error("failed " + src)); };
      document.head.appendChild(s);
    });
  }

  // load in order — later bundles read globals set by earlier ones
  function loadAll(names) {
    return names.reduce(function (chain, n) {
      return chain.then(function () { return loadScript(CDN + "/compiled/" + n + ".js"); });
    }, Promise.resolve());
  }

  function mountRoot() {
    var el = document.getElementById("page-root");
    if (el) return el;
    el = document.createElement("div");
    el.id = "page-root";
    var host = document.querySelector("main") || document.body;
    host.appendChild(el);
    return el;
  }

  function render(Comp, props) {
    if (!window.React || !window.ReactDOM) { console.error("[PagesRunner] React missing"); return; }
    if (!Comp) { console.error("[PagesRunner] component not found for " + currentPath()); return; }
    try {
      ReactDOM.createRoot(mountRoot()).render(React.createElement(Comp, props || null));
    } catch (err) {
      console.error("[PagesRunner] mount failed:", err);
    }
  }

